"""Renders a lowered program into the source of a generated agent package.

Output is deterministic: no timestamps, no set iteration, and the order of
every block comes from the lowered program. Regenerating the same spec yields
byte-identical files, which the golden tests rely on.
"""

from dataclasses import dataclass

import jinja2

from transpiler import __version__
from transpiler.codegen.filters import CodegenValueError, pyident, pyrepr, text_assignment
from transpiler.errors import Code, Diagnostic, Stage, TranspileError
from transpiler.lowering import AdkNode, AdkProgram
from transpiler.spec.models import START


@dataclass(frozen=True, slots=True)
class RenderedPackage:
    agent_py: str
    init_py: str


@dataclass(frozen=True, slots=True)
class _Imports:
    adk: list[str]
    apps: list[str]
    workflow: list[str]
    genai_types: bool
    runtime: list[str]
    bootstrap: list[str]
    models: bool


def _imports(program: AdkProgram) -> _Imports:
    uses_agent = program.uses("agent")
    workflow = []
    if program.uses("join"):
        workflow.append("JoinNode")
    if program.uses_retry_config:
        workflow.append("RetryConfig")
    bootstrap = []
    if program.services:
        bootstrap.append("HttpServiceConfig")
    if program.servers:
        bootstrap.append("McpServerConfig")
    if program.servers or program.services:
        bootstrap.append("RuntimeDeps")
    return _Imports(
        adk=["Agent", "Workflow"] if uses_agent else ["Workflow"],
        apps=["App", "ResumabilityConfig"] if program.needs_resumability else ["App"],
        workflow=workflow,
        genai_types=uses_agent,
        runtime=["guardrails", "nodes", "schemas"] if uses_agent else ["nodes"],
        bootstrap=bootstrap,
        models=uses_agent,
    )


def _source(var: str) -> str:
    return pyrepr(START) if var == START else pyident(var)


def _instruction_constant(node: AdkNode) -> str:
    if node.agent is None:  # pragma: no cover - only called for agent nodes
        raise CodegenValueError(f"{node.var} is not an agent")
    return pyident(f"{node.agent.key.upper()}_INSTRUCTION")


def _environment() -> jinja2.Environment:
    env = jinja2.Environment(
        loader=jinja2.PackageLoader("transpiler.codegen", "templates"),
        undefined=jinja2.StrictUndefined,
        autoescape=False,  # noqa: S701 - the output is Python source, not HTML
        keep_trailing_newline=True,
        trim_blocks=True,
        lstrip_blocks=True,
    )
    env.filters["pyrepr"] = pyrepr
    env.filters["pyident"] = pyident
    env.filters["source"] = _source
    env.filters["text_assignment"] = text_assignment
    env.filters["instruction_constant"] = _instruction_constant
    return env


def render(program: AdkProgram, *, spec_name: str) -> RenderedPackage:
    """Raises TranspileError(E_CODEGEN_RENDER) if a value cannot be emitted."""
    env = _environment()
    header = (
        f"# Generated by lab-transpile {__version__} from {spec_name} "
        f"(sha256: {program.spec_sha256}). DO NOT EDIT."
    )
    context = {
        "header": header,
        "program": program,
        "imports": _imports(program),
        "leaf_nodes": program.leaf_nodes(),
        "subworkflows": program.subworkflows(),
    }
    try:
        return RenderedPackage(
            agent_py=env.get_template("agent.py.j2").render(context),
            init_py=env.get_template("__init__.py.j2").render(context),
        )
    except CodegenValueError as exc:
        raise TranspileError(
            Stage.CODEGEN, [Diagnostic(code=Code.E_CODEGEN_RENDER, message=str(exc))]
        ) from exc
