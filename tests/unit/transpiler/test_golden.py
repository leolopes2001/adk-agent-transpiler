"""Generated packages for the versioned specs must match tests/golden byte for byte.

When a change to the transpiler is intended, regenerate with `make golden` and
review the diff of the golden files as part of the change.
"""

import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

from transpiler.codegen.render import render
from transpiler.emit import MANIFEST_NAME
from transpiler.pipeline import compile_spec, generate

pytestmark = pytest.mark.unit

ROOT = Path(__file__).parents[3]
GOLDEN = ROOT / "tests" / "golden"
SPECS = {
    "exam_scheduling_agent": Path("specs/exam_scheduling_agent.json"),
    "exam_lookup_only": Path("specs/examples/exam_lookup_only.json"),
}
FILES = ("agent.py", "__init__.py", MANIFEST_NAME)
REGENERATE = "run `make golden` and review the diff"


@pytest.fixture
def at_root(monkeypatch: pytest.MonkeyPatch) -> Path:
    # Manifests record the spec path relative to the working directory.
    monkeypatch.chdir(ROOT)
    return ROOT


@pytest.mark.parametrize("name", SPECS)
def test_generated_package_matches_golden(name: str, at_root: Path, tmp_path: Path) -> None:
    result = generate(SPECS[name], tmp_path / "out", allowed_root=tmp_path)

    assert sorted(p.name for p in result.path.iterdir()) == sorted(FILES)
    for filename in FILES:
        generated = (result.path / filename).read_bytes()
        golden = (GOLDEN / name / filename).read_bytes()
        assert generated == golden, f"{name}/{filename} differs from golden; {REGENERATE}"


@pytest.mark.parametrize("name", SPECS)
def test_generation_is_deterministic(name: str, at_root: Path) -> None:
    first = render(compile_spec(SPECS[name]).program, spec_name=SPECS[name].name)
    second = render(compile_spec(SPECS[name]).program, spec_name=SPECS[name].name)

    assert first == second


@pytest.mark.parametrize("name", SPECS)
def test_golden_is_ruff_formatted(name: str) -> None:
    for filename in ("agent.py", "__init__.py"):
        source = (GOLDEN / name / filename).read_text(encoding="utf-8")
        result = subprocess.run(  # noqa: S603 - fixed argv, runs the project's ruff
            [sys.executable, "-m", "ruff", "format", "--stdin-filename", filename, "-"],
            input=source,
            capture_output=True,
            text=True,
            check=True,
        )
        assert result.stdout == source, f"{name}/{filename} is not ruff-formatted"


@pytest.mark.parametrize("name", SPECS)
def test_golden_header_and_manifest(name: str, at_root: Path) -> None:
    compiled = compile_spec(SPECS[name])
    agent = (GOLDEN / name / "agent.py").read_text(encoding="utf-8")
    manifest = json.loads((GOLDEN / name / MANIFEST_NAME).read_text(encoding="utf-8"))

    assert agent.splitlines()[0].endswith(f"(sha256: {compiled.loaded.sha256}). DO NOT EDIT.")
    assert manifest["spec_sha256"] == compiled.loaded.sha256
    assert manifest["ir_digest"] == compiled.program.ir_digest
    assert manifest["spec_path"] == SPECS[name].as_posix()
    assert manifest["node_names"] == compiled.program.node_names()


def test_threshold_change_touches_only_its_literal(tmp_path: Path) -> None:
    shutil.copytree(ROOT / "specs", tmp_path / "specs")
    spec_path = tmp_path / "specs" / "exam_scheduling_agent.json"
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    gate = next(n for n in spec["workflow"]["nodes"] if n["id"] == "gate")
    gate["params"]["accept_threshold"] = 0.9
    spec_path.write_text(json.dumps(spec), encoding="utf-8")

    changed = render(compile_spec(spec_path).program, spec_name=spec_path.name).agent_py
    golden = (GOLDEN / "exam_scheduling_agent" / "agent.py").read_text(encoding="utf-8")

    differences = [
        (old, new)
        for old, new in zip(golden.splitlines(), changed.splitlines(), strict=True)
        if old != new
    ]
    assert len(differences) == 2
    header, literal = differences
    assert header[0].startswith("# Generated by lab-transpile")
    assert literal == ("    accept_threshold=0.85,", "    accept_threshold=0.9,")


def test_instruction_change_touches_only_the_instruction(tmp_path: Path) -> None:
    shutil.copytree(ROOT / "specs", tmp_path / "specs")
    instruction = tmp_path / "specs" / "instructions" / "exam_extractor.md"
    instruction.write_text(
        instruction.read_text(encoding="utf-8") + "6. Regra nova.\n", encoding="utf-8"
    )
    spec_path = tmp_path / "specs" / "exam_scheduling_agent.json"

    changed = render(compile_spec(spec_path).program, spec_name=spec_path.name).agent_py
    golden = (GOLDEN / "exam_scheduling_agent" / "agent.py").read_text(encoding="utf-8")

    added = set(changed.splitlines()) - set(golden.splitlines())
    assert added == {'    "6. Regra nova.\\n"'}
