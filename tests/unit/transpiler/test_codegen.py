def test_threshold_change_changes_only_its_literal(spec_dict: SpecDict) -> None:
    before = _render(spec_dict).agent_py.splitlines()
    spec_dict["workflow"]["nodes"][4]["params"]["accept_threshold"] = 0.9
    after = _render(spec_dict).agent_py.splitlines()

