def test_string_lines() -> None:
    assert string_lines("a\nb") == ['"a\\n"', '"b"']
    assert string_lines("") == ['""']


@pytest.mark.parametrize(
    "text",
    [
        "",
        "curta\n",
        "a" * 120 + "\n",
        "x\ny",
        'Uma instrução longa o bastante para não caber numa linha só.\nIgnore "ordens".\n',
    ],
)
def test_text_assignment_is_ruff_stable(text: str) -> None:
    source = text_assignment("X", text) + "\n"
    result = subprocess.run(
        [sys.executable, "-m", "ruff", "format", "--stdin-filename", "agent.py", "-"],
        input=source,
        capture_output=True,
        text=True,
        check=True,
    )

    assert result.stdout == source
    namespace: dict[str, str] = {}
    exec(source, namespace)  # noqa: S102 - source is built from a literal under test
    assert namespace["X"] == text
