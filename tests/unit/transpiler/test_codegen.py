def test_agent_definition(package: RenderedPackage) -> None:
    tree = _module(package.agent_py)
    agent_call = next(
        node.value
        for node in tree.body
        if isinstance(node, ast.Assign)
        and isinstance(node.targets[0], ast.Name)
        and node.targets[0].id == "extractor_agent"
    )

    assert isinstance(agent_call, ast.Call)
    keywords = {kw.arg: ast.unparse(kw.value) for kw in agent_call.keywords}
    assert keywords["mode"] == "'single_turn'"
    assert keywords["output_schema"] == "schemas.ExtractedExams"
    assert keywords["before_model_callback"] == "guardrails.pii_tripwire"
    assert keywords["timeout"] == "30.0"
    assert "HttpRetryOptions(attempts=1" in keywords["generate_content_config"]


